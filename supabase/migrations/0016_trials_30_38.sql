Two easy sessions, four hours apart, in one day. Recovery between efforts is a skill of its
own, and this is the first time it's tested on purpose.

**THE WORK**

1. Do two separate movement sessions in one day, at least four hours apart — walking, the Stack, anything you've already done here.
