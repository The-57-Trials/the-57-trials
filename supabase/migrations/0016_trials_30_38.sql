update public.trials set
  title      = 'THE HUNDRED',
  trial_type = 'MOVE',
  flag       = 'AMBER',
  body_md    = $md$**THE LINE**

A hundred reps of one movement, spread across a whole day, ten at a time at most. Volume
without ever letting a single set get hard.

**THE WORK**

1. Pick one simple movement from the Stack — sit-to-stand, wall press, hinge, march — whichever suits where you'll be today.
2. Do sets of up to ten, spread across the entire day, however many sets it takes to reach a hundred total reps.
3. Never more than ten in a single set. Ten, then rest — however long the rest is, a minute or three hours, doesn't matter.
4. Fit sets in wherever your day allows: waiting for the kettle, between meetings, whenever you think of it.
5. Log the total once you've reached a hundred.

**THE RUBRIC**

*RISK* — Chaining sets back to back without real rest between them, which turns this into an
intensity trial it was never meant to be. Fatigue building across the day if the movement
chosen is more demanding than it seemed at ten reps.

*GROUND* — Whatever the chosen movement needs, wherever you happen to be across the day —
this one's designed to fit around an ordinary day rather than needing a dedicated session.

*STOP* — The usual four constants, plus: stop for the day on any joint pain that builds
across the sets rather than settling — that's a sign the movement or the day's total needs
to be smaller, not pushed through.

*SCALE* — Fifty reps instead of a hundred, same rule of ten per set maximum · spread it
across two days if a single day genuinely doesn't have the pockets of time.

*CLEARED WHEN* — A hundred reps, or fifty scaled, are logged, in sets of ten or fewer.

**NOTE**

By set six or seven most people stop noticing they're doing it. That's the volume working,
not you switching off.$md$
