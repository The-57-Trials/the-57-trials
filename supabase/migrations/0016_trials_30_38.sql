that doesn't settle within a minute of stopping · dizziness that doesn't clear when you sit
down · any sharp or new pain. Also turn back and try indoors instead if the ground or
lighting doesn't feel safe once you're out there.

*SCALE* — Choose an indoor session if outdoor darkness doesn't feel safe · a shorter version
of whichever session you picked, provided it still finishes before sunrise.

*CLEARED WHEN* — The session is finished before sunrise, logged the same day.

**NOTE**

Almost nobody else is awake for this one. That's most of what makes it feel different.$md$
