  title      = 'THE THIRD HOUR',
  trial_type = 'MOVE',
  flag       = 'AMBER',
  body_md    = $md$**THE LINE**

Three hours on your feet, at conversational effort. Not a hike, not a race — a long,
deliberately boring block of time in which nothing dramatic should happen. Read this today,
do the trial another day.

**THE WORK**

1. Plan a route on ground you know, with at least one point partway where you could stop and get home if you needed to. Share it with someone before you leave, and roughly what time you'll be back.
2. Walk for three hours at a pace you could hold a conversation through. No pace target, no distance target — time on your feet is the exercise.
3. Stop for a few minutes every forty-five minutes or so, whether you need it or not.
4. Carry food and water, and actually use them — eat something at around ninety minutes, not only if you feel hungry.
5. Check your feet if anything starts to feel hot or rubbing. A hot spot caught early is nothing; caught late, it's a limp for the last hour.

**THE RUBRIC**

*RISK* — Underfuelling, which shows up as light-headedness or poor decisions well before
you'd call yourself tired. Blisters, from new shoes or a hot spot ignored. Getting caught out
by weather or fading light on a route that runs longer than expected.

*GROUND* — A known route, made paths or pavement, with a genuine way to shorten it or get
home if you need to. Postpone for thunderstorms, ice, or any weather warning; layer up or
plan shade for genuine heat.

*STOP* — Stop for the day if any of these happen: chest pain or tightness · breathlessness
that doesn't settle within a minute of stopping · dizziness that doesn't clear when you sit
down · any sharp or new pain. Also stop for any blister that's actually formed, if you're
cold and can't warm up after a stop, or if the route is running into darkness you didn't
plan for. Using a bail-out partway is a correctly executed trial, not a failed one.

*SCALE* — Any of these clears the trial: two hours instead of three, same rules · two blocks
of ninety minutes with a proper meal between · a loop close to home walked several times
over — genuinely safer than a long point-to-point.

*CLEARED WHEN* — The time you set out to do is walked, at conversational effort, with stops
taken and food and water used.

**NOTE**

Trial 52 is this again, longer, with a witness. This one is the rehearsal.$md$
