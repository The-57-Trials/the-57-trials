Trial 01 asked what would make you quit. This is the thing you've built a whole life around
avoiding. Not a longer walk — the one thing, whatever it actually is.

**PRE-FLIGHT** — every line must be true.

- **Named and written down**, before you plan how — the specific thing, not a category. "Speak in public" isn't specific. "Say the toast at my brother's wedding" is.
- **A real reason written alongside it**, beyond "it scares me." If you can't find one, it's probably still the right thing — write that down too.
- **Planned properly for what it actually is.** If it's physical, the same standards as every trial since 48: route, bail-outs, food, water, weather — and the same limits as everything else in this book. No climbing, no open water, no heights, nothing that breaks a rule the rest of the 57 has kept. If it isn't, a real date, a real place, and a plan specific enough that you can't quietly downgrade it on the day.
- **Nothing here needs professional help instead of a personal trial.** If what you've named involves a health, legal or financial matter serious enough to need a professional, that's not this trial — name something else.
- **Named witness and check-in agreed**, the same as every trial since 48.

If any line is false: postpone. This is not the trial to compromise on.

**THE WORK**

1. Decide what your last ground actually is. It might be physical — further than anything before it. It might not be. It's the one thing you have organised your life around not doing: standing up and speaking in front of a room, taking the first real step on the thing you've delayed for years, having the conversation you've never had, sending what you've never sent, asking what you've never asked, raising money publicly for something that matters to you. Yours to name. Not ours.
2. Write down what it is and why it's the one, before you plan how.
3. Plan it properly for whatever kind of thing it is — see PRE-FLIGHT.
4. Name a witness and agree how they'll hear from you, before and after.
5. Do the thing, however it goes. This isn't the trial to find out what you have left. It's the trial where you already know, and you do it anyway.

**THE RUBRIC**

*RISK* — If it's physical: everything the walking trials before it have carried. If it isn't:
the risk is talking yourself out of it in the final minutes — exactly the pattern this whole
product has been built to interrupt.

*GROUND* — Whatever your last ground actually needs. If physical, the standards set from
Trial 48 onward, without exception. If not, a setting where you can actually go through with
it — a real room and a real audience, not a rehearsal in the mirror.

*STOP* — The usual four physical constants if this is physical: chest pain or tightness ·
breathlessness that doesn't settle within a minute of stopping · dizziness that doesn't
clear when you sit down · any sharp or new pain. Whatever it is, if it turns out to need
professional support rather than a personal trial, that's not a failure of the trial — it's
the trial doing exactly the job the STOP field has always done. Postponing a declared finish
for a genuine reason is not a failure — it's the same judgement this whole product has asked
for since Trial 01.

*SCALE* — There is no scale field. You set your own scale the moment you decided what this
was. A five-minute conversation and a speech to a full room can both be someone's last
ground, honestly chosen.

*CLEARED WHEN* — The thing you named is done, and you've reported to your witness.

**CHECK-IN** — not optional, adapted to what you're doing: a route and finish time if it's
physical, a date and outcome if it isn't.

