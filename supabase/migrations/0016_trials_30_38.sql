One day with no numbers about yourself — no steps, no weight, no calories, no streak, no
scores. See what's left to notice when the counting stops.

**THE WORK**

1. Pick one day. For that whole day, don't look at any number that measures you — no step count, no scale, no calorie total, no screen time report, no trial streaks, nothing quantified about your own body or behaviour.
2. If a number appears without you asking for it — a notification, a glance at a smartwatch face — that's fine, you're not being tested on avoiding your own eyes. The instruction is not to seek it out.
3. Notice instead, if you want to: how you feel, what you did, what mattered, without translating any of it into a figure.
4. At the end of the day, don't total anything up. There's no number to report back, on purpose.
5. Log that the day happened, once it's over.

**THE RUBRIC**

*RISK* — Physically none. The real difficulty is habit — reaching for a number is often
automatic, not a decision, and noticing that is most of what this trial teaches.

*GROUND* — Nothing physical. A day where checking a number isn't safety-critical — if you
manage a medical condition that requires tracking a number, that tracking is exempt and this
trial doesn't ask you to stop it.

*STOP* — There's no way to fail this by trying too hard. If the day genuinely can't work
today, pick a different day this week instead.

*SCALE* — A half-day instead of a full one, if a full day genuinely isn't practical this
week.

*CLEARED WHEN* — A full day, or the half-day scale, has passed without seeking out a number
about yourself.

**NOTE**

Nobody has ever come back from this trial with a number to report. That's not a failure of
memory.$md$
