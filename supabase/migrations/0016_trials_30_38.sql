tightness · breathlessness that doesn't settle within a minute of stopping · dizziness that
doesn't clear when you sit down · any sharp or new pain. A stop on session one doesn't
cancel session two later in the day, and vice versa.

*SCALE* — Two hours apart instead of four, if your day genuinely doesn't allow more
separation · ten minutes each instead of fifteen to thirty.

*CLEARED WHEN* — Two sessions are logged on the same day, at least the minimum gap apart.

**NOTE**

The second session almost always feels different from the first. That difference is the
point of the trial.$md$
