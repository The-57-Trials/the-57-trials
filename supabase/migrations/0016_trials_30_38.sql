  body_md    = $md$**THE LINE**

The conversation you've been putting off. Not a fight — the one honest exchange you keep
rehearsing in the shower and never having.

**THE WORK**

1. Identify one overdue conversation — something you need to say to someone, or ask someone, that you've been avoiding for weeks or longer.
2. Have it. In person or by call, not by text if you can help it — this is about saying it, not drafting it.
3. Say the actual thing, not a softened version of it. You can be kind about how you say it; you can't leave out the point of it.
4. Afterward, write a few honest lines about how it went — not to justify yourself, just what was actually said and how it landed.
5. However it goes, having the conversation clears the trial. The outcome isn't graded.

**THE RUBRIC**

*RISK* — Picking something low-stakes to avoid the real one, which defeats the trial.
Turning it into an ambush rather than a conversation — give the other person some warning
that you want to talk, where that's kind to do.

*GROUND* — Nothing physical. Choose a setting where you can both actually hear each other
and neither of you needs to leave abruptly.

*STOP* — If the honest conversation risks someone's safety, or is about something serious
enough to need a professional rather than a personal conversation, that's not this trial —
pick a different overdue conversation instead.

*SCALE* — A written version — a proper letter or message, not a one-line text — clears this
if speaking genuinely isn't possible or safe. The honesty is the requirement, not the medium.

*CLEARED WHEN* — The conversation has happened, and a few honest lines about it are written.

**NOTE**

The rehearsed version in your head is never the one that actually happens. That's fine.$md$
