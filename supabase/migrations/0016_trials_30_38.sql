Ten small promises made to yourself at dawn, checked against what actually happened by
night. A day-long version of the pledge from Trial 03.

**THE WORK**

1. First thing in the morning, write down ten small promises for the day — specific, achievable things, not vague intentions. "Reply to that email," not "be more on top of things."
